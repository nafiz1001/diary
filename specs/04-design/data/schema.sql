-- Standard SQL. An implementation may translate the identity column syntax
-- and map CLOB to its unlimited text type.
--
-- Instants: UTC. An implementation that stores an instant as text writes it as
-- 'YYYY-MM-DD HH:MM:SS.ffffff' (microseconds, no zone marker), so that text order
-- equals time order.
--
-- Rules that live in the application, not here:
--   * entry_text is not whitespace only for submit and update (BR-SUB-1, TS-TEXT-5).
--     SQL TRIM does not remove tabs or line breaks, and imported rows may break the rule.
--   * created_at never changes (INV-2). updated_at equals created_at until the first update (INV-3).
--
-- The identity column must continue after the highest id that the import wrote (BR-IMP-2).
--
-- schema_version holds exactly one row: the schema version of this store (REQ-NFR-008, ADR-0009).
-- A migration from version n to n + 1 updates the row in the same transaction as its changes.

CREATE TABLE entries (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_text  CLOB NOT NULL,
    created_at  TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP NOT NULL
);

-- Serves the order "creation instant, then id" in both directions (BR-BRW-1, BR-EXP-1)
-- and the filter "created at or after" (TS-DATE-4).
CREATE INDEX entries_created_at_id_idx ON entries (created_at, id);

-- One row. The CHECK keeps it to one row. The version of this file is 1 (TS-STORE-1).
CREATE TABLE schema_version (
    singleton  INTEGER NOT NULL PRIMARY KEY CHECK (singleton = 1),
    version    INTEGER NOT NULL CHECK (version >= 1)
);

