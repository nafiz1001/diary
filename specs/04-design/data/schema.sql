-- Standard SQL. An implementation may translate the identity column syntax
-- and map CLOB to its unlimited text type.
-- All timestamps are UTC.
-- The rule "text is not whitespace only" (BR-SUB-1) lives in the application,
-- because SQL TRIM does not remove tabs or line breaks.

CREATE TABLE entries (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_text  CLOB NOT NULL,
    created_at  TIMESTAMP NOT NULL
);

CREATE INDEX entries_created_at_idx ON entries (created_at);
